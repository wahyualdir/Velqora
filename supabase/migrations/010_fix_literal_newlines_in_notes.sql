-- ============================================================
-- Migration 010: Fix Literal Newlines in Legacy Notes
-- Velqora Academic Knowledge Base
-- ============================================================

-- Mengganti literal '\n' (karakter backslash + n dari string literal migrasi 008)
-- menjadi baris baru sungguhan (chr(10)) pada 14 catatan awal kurikulum.
-- Query ini aman dijalankan berulang (idempotent).
UPDATE notes
SET content_markdown = replace(content_markdown, '\n', chr(10))
WHERE id IN (
  '00000000-0000-0000-0001-000000000001', '00000000-0000-0000-0001-000000000002',
  '00000000-0000-0000-0001-000000000003', '00000000-0000-0000-0001-000000000004',
  '00000000-0000-0000-0001-000000000005', '00000000-0000-0000-0001-000000000006',
  '00000000-0000-0000-0001-000000000007', '00000000-0000-0000-0001-000000000008',
  '00000000-0000-0000-0001-000000000009', '00000000-0000-0000-0001-000000000010',
  '00000000-0000-0000-0001-000000000011',
  '00000000-0000-0000-0002-000000000001', '00000000-0000-0000-0002-000000000002',
  '00000000-0000-0000-0002-000000000003'
);
